"""Prepare leadership headshots for the site.

For every photo in assets/headshots/ (the top level only; the originals are never changed):
  1. find the face (OpenCV's frontal-face detector) and crop a square around it, so every
     portrait has the face at the same size and height in the frame;
  2. even out exposure and contrast across the set: each photo's brightness is matched on the face,
     and its contrast on the whole crop, to the group's typical values;
  3. save a 900 x 900 JPEG to assets/headshots/web/<name>.jpg and list everyone in
     data/leadership.js, named from the file names.

Usage (from the repo root):  python tools/process-headshots.py
Needs:  python -m pip install --user "opencv-python-headless<5" pillow   (OpenCV 5 dropped this face detector)
"""
import json
import re
import sys
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "headshots"
OUT = SRC / "web"
DATA = ROOT / "data" / "leadership.js"

SIZE = 900            # output pixels
FACE_SHARE = 0.32     # the detected face is this share of the crop's height
FACE_CENTRE_Y = 0.45  # where the face centre sits in the crop (0 top, 1 bottom)

detector = cv2.CascadeClassifier(cv2.data.haarcascades + "haarcascade_frontalface_default.xml")


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def display_name(stem):
    return re.sub(r"\s+", " ", stem).strip()


def find_face(rgb):
    grey = cv2.cvtColor(rgb, cv2.COLOR_RGB2GRAY)
    h, w = grey.shape
    min_side = int(min(h, w) * 0.08)
    faces = detector.detectMultiScale(grey, scaleFactor=1.08, minNeighbors=6, minSize=(min_side, min_side))
    if len(faces) == 0:
        return None
    return max(faces, key=lambda f: f[2] * f[3])  # the largest face is the subject


def crop_square(rgb, face):
    h, w = rgb.shape[:2]
    if face is None:  # fall back to the upper middle of the frame
        side = min(h, w)
        cx, cy = w / 2, side / 2
        fy0, fy1 = int(h * 0.2), int(h * 0.5)
    else:
        fx, fy, fw, fh = face
        side = fh / FACE_SHARE
        cx, cy = fx + fw / 2, fy + fh / 2 + (0.5 - FACE_CENTRE_Y) * side
        fy0, fy1 = fy, fy + fh
    side = min(side, h, w)
    x0 = int(round(min(max(cx - side / 2, 0), w - side)))
    y0 = int(round(min(max(cy - side / 2, 0), h - side)))
    s = int(round(side))
    crop = rgb[y0:y0 + s, x0:x0 + s]
    # The face box inside the crop, for measuring exposure on the face.
    if face is None:
        box = (int(s * 0.3), int(s * 0.25), int(s * 0.4), int(s * 0.35))
    else:
        box = (int(face[0] - x0), int(face[1] - y0), int(face[2]), int(face[3]))
    return crop, box, face is not None


def lightness_stats(crop, box):
    lab = cv2.cvtColor(crop, cv2.COLOR_RGB2LAB).astype(np.float32)
    L = lab[:, :, 0]
    x, y, w, h = box
    face = L[max(0, y):y + h, max(0, x):x + w]
    return float(face.mean()), float(L.std())


def equalise(crop, box, face_target, std_target):
    lab = cv2.cvtColor(crop, cv2.COLOR_RGB2LAB).astype(np.float32)
    L = lab[:, :, 0]
    face_mean, std = lightness_stats(crop, box)
    gain = np.clip(std_target / max(std, 1.0), 0.75, 1.35)  # keep corrections gentle
    L = (L - face_mean) * gain + face_target
    lab[:, :, 0] = np.clip(L, 0, 255)
    return cv2.cvtColor(lab.astype(np.uint8), cv2.COLOR_LAB2RGB)


def main():
    files = sorted(p for p in SRC.iterdir() if p.is_file() and p.suffix.lower() in {".jpg", ".jpeg", ".png"})
    if not files:
        sys.exit("No photos found in " + str(SRC))
    OUT.mkdir(exist_ok=True)

    items = []
    for p in files:
        img = ImageOps.exif_transpose(Image.open(p)).convert("RGB")
        rgb = np.array(img)
        crop, box, found = crop_square(rgb, find_face(rgb))
        items.append({"path": p, "crop": crop, "box": box, "found": found})
        print(f"{p.name}: face {'found' if found else 'NOT found, used the upper middle'}")

    stats = [lightness_stats(i["crop"], i["box"]) for i in items]
    face_target = float(np.median([s[0] for s in stats]))
    std_target = float(np.median([s[1] for s in stats]))
    print(f"targets: face lightness {face_target:.1f}, contrast {std_target:.1f}")

    leaders = []
    for i in items:
        out = equalise(i["crop"], i["box"], face_target, std_target)
        out = cv2.resize(out, (SIZE, SIZE), interpolation=cv2.INTER_AREA)
        name = display_name(i["path"].stem)
        file = slug(name) + ".jpg"
        Image.fromarray(out).save(OUT / file, quality=86, optimize=True, progressive=True)
        leaders.append({"name": name, "headshot": "web/" + file})

    entries = ",\n".join("  " + json.dumps(l) for l in leaders)
    DATA.write_text(
        "/*\n"
        "  Leadership roster for the Contact page, generated by tools/process-headshots.py from the\n"
        "  photos in assets/headshots/. Names come from the file names. Add `role` and `area` to an\n"
        "  entry to show them on the card; re-running the script rewrites this file.\n"
        "*/\n"
        "window.LEADERSHIP = [\n" + entries + "\n];\n",
        encoding="utf-8",
    )
    print(f"wrote {len(leaders)} portraits to {OUT.relative_to(ROOT)} and {DATA.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
